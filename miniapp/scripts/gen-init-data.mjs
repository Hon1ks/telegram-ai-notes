#!/usr/bin/env node
/**
 * Generates Telegram WebApp initData for local browser preview.
 * Reads TELEGRAM_TOKEN from notes-bot/.dev.vars or TELEGRAM_TOKEN env.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHmac } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '../..');

function readToken() {
  if (process.env.TELEGRAM_TOKEN?.trim()) {
    return process.env.TELEGRAM_TOKEN.trim();
  }

  const devVarsPath = resolve(root, 'notes-bot/.dev.vars');
  if (!existsSync(devVarsPath)) {
    console.error('TELEGRAM_TOKEN not found.');
    console.error('Create notes-bot/.dev.vars from .dev.vars.example or set TELEGRAM_TOKEN env.');
    process.exit(1);
  }

  const match = readFileSync(devVarsPath, 'utf8').match(/^TELEGRAM_TOKEN=(.+)$/m);
  if (!match?.[1]?.trim()) {
    console.error('TELEGRAM_TOKEN is empty in notes-bot/.dev.vars');
    process.exit(1);
  }
  return match[1].trim();
}

function createInitData(botToken, authDate, userId, firstName) {
  const params = new URLSearchParams({
    auth_date: String(authDate),
    query_id: 'dev-preview',
    user: JSON.stringify({ id: userId, first_name: firstName, username: 'dev_user' }),
  });

  const dataCheckString = [...params.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');

  const secretKey = createHmac('sha256', 'WebAppData').update(botToken).digest();
  const hash = createHmac('sha256', secretKey).update(dataCheckString).digest('hex');
  params.set('hash', hash);
  return params.toString();
}

const userId = Number(process.argv[2] ?? process.env.DEV_USER_ID ?? '123456789');
const firstName = process.argv[3] ?? 'Dev User';
const token = readToken();
const authDate = Math.floor(Date.now() / 1000);
const initData = createInitData(token, authDate, userId, firstName);

const envPath = resolve(__dirname, '../.env.development.local');
const content = [
  '# Auto-generated by npm run gen:auth — do not commit',
  `VITE_DEV_INIT_DATA=${initData}`,
  `VITE_DEV_USER_ID=${userId}`,
  `VITE_DEV_USER_NAME=${firstName}`,
  '',
].join('\n');

writeFileSync(envPath, content, 'utf8');

console.log('✓ Dev auth written to miniapp/.env.development.local');
console.log(`  user_id: ${userId}`);
console.log(`  auth_date: ${authDate}`);
console.log('');
console.log('Next:');
console.log('  1. cd notes-bot && npm run dev   (API on :8787)');
console.log('  2. cd miniapp && npm run dev:web (UI on :5173)');